/** Cells of one line of text, as [column, row] pairs. Unknown characters are spaces. */
export function textCells(text: string): [number, number][] {
  const cells: [number, number][] = []
  ;[...text].forEach((ch, i) => {
    const glyph = GLYPHS[ch]
    if (!glyph) return
    glyph.forEach((row, y) =>
      [...row].forEach((c, x) => {
        if (c === "#") cells.push([i * 6 + x, y])
      })
    )
  })
  return cells
}
